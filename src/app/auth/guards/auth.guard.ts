import { inject } from '@angular/core';
import { CanActivateFn, Router } from '@angular/router';
import { AuthService } from '../services/auth.service';

/**
 * Protects routes requiring authentication (e.g. /dashboard)
 * If unauthenticated or after logout, strictly denies access and redirects to /login.
 */
export const authGuard: CanActivateFn = () => {
  const authService = inject(AuthService);
  const router = inject(Router);

  if (authService.isAuthenticated()) {
    return true;
  }

  // Deny access and redirect to login, replacing browser history entry
  return router.createUrlTree(['/login']);
};

/**
 * Prevents authenticated users from seeing the /login page again
 * Automatically forwards logged-in users to /dashboard.
 */
export const guestGuard: CanActivateFn = () => {
  const authService = inject(AuthService);
  const router = inject(Router);

  if (authService.isAuthenticated()) {
    return router.createUrlTree(['/dashboard']);
  }

  return true;
};
